#include <stdio.h>

int main(void)
{
    int n;

    printf("Введите N (N <= 0 для выхода): ");
    while (scanf("%d", &n) == 1 && n > 0) {
        double sum = 0.0;   
        double p = 1.0;   
        int i;

        for (i = 1; i <= n; i++) {
            p *= 2.0;
            sum += (double)i * i / p;
        }
        printf("SUM: %.6f\n", sum);
        printf("Введите N (N <= 0 для выхода): ");
    }

    /*
     * Пояснение: аккумулятор инициализируется 0.0 (double), потому что сумма
     * вещественная. Если объявить int sum = 0, дробная часть каждого
     * слагаемого будет отбрасываться при присваивании, и результат окажется
     * неверным. Начальное значение 0.0 также гарантирует, что все сложения
     * выполняются в арифметике двойной точности.
     */
    return 0;
}
