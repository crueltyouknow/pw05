#include <stdio.h>

#define SIZE 8

int main(void)
{
    double arr[SIZE];
    int i;

    for (i = 0; i < SIZE; i++) {
        arr[i] = 1.0 + 2.0 * i; 
    }

    for (i = 0; i < SIZE; i++) {
        printf("%.2f ", arr[i]);
    }
    printf("\n");

    for (i = SIZE - 1; i >= 0; i--) {
        printf("%.2f ", arr[i]);
    }
    printf("\n");

    /*
     * Пояснение: индексация с нуля связана с тем, что arr[i] означает
     * "адрес начала массива плюс i элементов": *(arr + i). Первый элемент
     * лежит в самом начале массива, то есть смещение от начала равно 0.
     * Запись arr[i] эквивалентна *(arr + i); указатель сам по себе хранит
     * адрес, а индекс задает смещение от него в элементах.
     */
    return 0;
}
