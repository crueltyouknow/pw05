#include <stdio.h>

#define HEIGHT 5

int main(void)
{
    const int WIDTH = 5;
    int i, j;

    for (i = 0; i < HEIGHT; i++) {          
        for (j = 0; j < WIDTH; j++) {       
            if (i % 2 == 0 && j % 2 == 0) {
                putchar('+');               
            } else {
                putchar('-');               
            }
        }
        putchar('\n');
    }

    /*
     * Пояснение: счетчик внешнего цикла i задает номер строки и растет от 0
     * до HEIGHT-1. Счетчик внутреннего цикла j при каждом новом i начинает с
     * нуля и пробегает все столбцы строки. Символ выбирается по четности i и
     * j: на четных строках и четных столбцах стоит '+', во всех остальных
     * позициях '-'. Так чередуются строки "+-+-+" и "-----".
     */
    return 0;
}
